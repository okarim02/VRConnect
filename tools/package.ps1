# tools/package.ps1 -- Build VRConnect and create a clean deployment zip.
#
# Usage:
#   .\tools\package.ps1                           -- build + zip
#   .\tools\package.ps1 -SkipBuild               -- zip only (reuse last cargo build)
#   .\tools\package.ps1 -SourceDeploy "D:\other" -- use a different reference folder
#   .\tools\package.ps1 -OutDir "C:\releases"    -- output zip to a custom folder
#
# The zip excludes: logs/, data/, recordings/, powershell/logs/, .env, .claude/, ~$* temp files.

param(
    # Default: deploy/ of the Alison-docs repo (alison_utbm_3y\Projets\VRConnect next to alison_utbm_3y\docs\Alison-docs)
    [string]$SourceDeploy = (Join-Path $PSScriptRoot "..\..\..\docs\Alison-docs\deploy"),
    [string]$OutDir       = "",
    [switch]$SkipBuild
)

$ErrorActionPreference = "Stop"
$ProjectRoot = Split-Path $PSScriptRoot -Parent
$ReleaseBin  = Join-Path $ProjectRoot "target\release\vrconnect.exe"

if (-not $OutDir) { $OutDir = Join-Path $ProjectRoot "dist" }

# Step 0: deployment scripts must come from Alison master. They are copied from the
# working tree, so a feature branch silently ships stale scripts (2026-10-01: a zip
# built while Alison was on graphify-knowledge-graph shipped a Setup.bat missing the
# HealthWriter start fixed on master in 2e012ee -> health vr=0/wd=0 on the target).
# deploy/ is a subfolder of the repo, so ask git rather than look for .git here.
if ((git -C $SourceDeploy rev-parse --is-inside-work-tree 2>$null) -eq "true") {
    $srcBranch = (git -C $SourceDeploy branch --show-current 2>$null)
    if ($srcBranch -ne "master") {
        Write-Host "[FAIL] $SourceDeploy is on branch '$srcBranch', not 'master'." -ForegroundColor Red
        Write-Host "       Switch it to master (git -C `"$SourceDeploy`" switch master) and retry." -ForegroundColor Red
        exit 1
    }
}

# Step 1: build
if (-not $SkipBuild) {
    Write-Host "[1/4] cargo build --release..." -ForegroundColor Cyan
    Push-Location $ProjectRoot
    cargo build --release
    if ($LASTEXITCODE -ne 0) {
        Write-Host "[FAIL] Build failed." -ForegroundColor Red; exit 1
    }
    Pop-Location
} else {
    Write-Host "[1/4] Skipping build (-SkipBuild)." -ForegroundColor DarkGray
}

if (-not (Test-Path $ReleaseBin)) {
    Write-Host "[FAIL] vrconnect.exe not found at $ReleaseBin" -ForegroundColor Red; exit 1
}
$exeSizeMB = [Math]::Round((Get-Item $ReleaseBin).Length / 1MB, 1)
Write-Host "      vrconnect.exe: $exeSizeMB MB" -ForegroundColor Green

# Step 2: version tag
Push-Location $ProjectRoot
$gitSha = (git log --format="%h" -1 2>$null).Trim()
if (-not $gitSha) { $gitSha = "nosha" }
Pop-Location
$dateTag    = Get-Date -Format "yyyy-MM-dd"
$zipName    = "VRConnect-Deploy-$dateTag-$gitSha"
$stagingDir = Join-Path $env:TEMP $zipName

Write-Host "[2/4] Staging to $stagingDir..." -ForegroundColor Cyan

if (Test-Path $stagingDir) { Remove-Item $stagingDir -Recurse -Force }
New-Item -ItemType Directory -Path $stagingDir | Out-Null

# Step 3: copy files
Write-Host "[3/4] Copying deployment files..." -ForegroundColor Cyan

# Binary (from fresh build)
Copy-Item $ReleaseBin (Join-Path $stagingDir "vrconnect.exe")
Write-Host "  + vrconnect.exe ($exeSizeMB MB)" -ForegroundColor DarkGray

# Root scripts (AGENTS.md/CLAUDE.md are AI-agent memory files -- internal dev
# tooling, never shipped to a deployment target)
foreach ($f in @("Install.ps1", "Setup.bat", "Stop.bat")) {
    $src = Join-Path $SourceDeploy $f
    if (Test-Path $src) {
        Copy-Item $src (Join-Path $stagingDir $f)
        Write-Host "  + $f" -ForegroundColor DarkGray
    } else {
        Write-Host "  ? $f not found in SourceDeploy (skipped)" -ForegroundColor Yellow
    }
}

# Deployment docs -- per docs/CONTEXT.md's own inventory, the DEX (Dossier
# d'Exploitation, CHU-facing) PDF and the field SOP guide belong in the zip.
# Both moved under docs/ during the 2026-08-21 doc consolidation, then to
# docs/vrconnect/deploiement/ on 2026-10-12; docs/ sits next to deploy/.
foreach ($f in @("DEX-VRConnect-VitalRecorder-v2.0.0.pdf", "DEPLOYMENT.md")) {
    $src = Join-Path $SourceDeploy "..\docs\vrconnect\deploiement\$f"
    if (Test-Path $src) {
        Copy-Item $src (Join-Path $stagingDir $f)
        Write-Host "  + $f" -ForegroundColor DarkGray
    } else {
        Write-Host "  ? $f not found in docs\vrconnect\deploiement\ (skipped)" -ForegroundColor Yellow
    }
}

# VitalRecorder executables
foreach ($f in @("Vital.exe", "VitalSync.exe", "VitalUtils.exe")) {
    $src = Join-Path $SourceDeploy $f
    if (Test-Path $src) {
        Copy-Item $src (Join-Path $stagingDir $f)
        Write-Host "  + $f" -ForegroundColor DarkGray
    }
}

# config/ -- copy all files except .env (generated by Install.ps1 from config.toml)
$configSrc = Join-Path $SourceDeploy "config"
$configDst = Join-Path $stagingDir "config"
New-Item -ItemType Directory -Path $configDst | Out-Null
Get-ChildItem $configSrc -Recurse -File |
    Where-Object { $_.Name -ne ".env" -and $_.Name -notlike "~`$*" -and $_.FullName -notlike "*\vrconnect-3000-bx50\*" } |
    ForEach-Object {
        $rel    = $_.FullName.Substring($configSrc.Length + 1)
        $dst    = Join-Path $configDst $rel
        $dstDir = Split-Path $dst -Parent
        if (-not (Test-Path $dstDir)) { New-Item -ItemType Directory -Path $dstDir | Out-Null }
        Copy-Item $_.FullName $dst
        Write-Host "  + config\$rel" -ForegroundColor DarkGray
    }

# powershell/ scripts -- skip powershell\logs\
$psSrc = Join-Path $SourceDeploy "powershell"
$psDst = Join-Path $stagingDir "powershell"
New-Item -ItemType Directory -Path $psDst | Out-Null
Get-ChildItem $psSrc -Recurse -File |
    Where-Object { $_.FullName -notlike "*\logs\*" -and $_.Name -notlike "~`$*" } |
    ForEach-Object {
        $rel    = $_.FullName.Substring($psSrc.Length + 1)
        $dst    = Join-Path $psDst $rel
        $dstDir = Split-Path $dst -Parent
        if (-not (Test-Path $dstDir)) { New-Item -ItemType Directory -Path $dstDir | Out-Null }
        Copy-Item $_.FullName $dst
        Write-Host "  + powershell\$rel" -ForegroundColor DarkGray
    }

# utilities/ executables + drivers/ (FTDI USB-serial driver installer for the BX50 cable;
# *.exe are git-ignored in the Alison repo, so drivers/ lives in its working tree like Vital.exe)
foreach ($d in @("utilities", "drivers")) {
    $utilSrc = Join-Path $SourceDeploy $d
    $utilDst = Join-Path $stagingDir $d
    if (-not (Test-Path $utilSrc)) {
        Write-Host "  ? $d\ not found in SourceDeploy (skipped)" -ForegroundColor Yellow
        continue
    }
    New-Item -ItemType Directory -Path $utilDst | Out-Null
    Get-ChildItem $utilSrc -Recurse -File | ForEach-Object {
        $rel    = $_.FullName.Substring($utilSrc.Length + 1)
        $dst    = Join-Path $utilDst $rel
        $dstDir = Split-Path $dst -Parent
        if (-not (Test-Path $dstDir)) { New-Item -ItemType Directory -Path $dstDir | Out-Null }
        Copy-Item $_.FullName $dst
        Write-Host "  + $d\$rel" -ForegroundColor DarkGray
    }
}

# example.env from project root (template -- .env is generated by Install.ps1)
$exampleEnv = Join-Path $ProjectRoot "example.env"
if (Test-Path $exampleEnv) {
    Copy-Item $exampleEnv (Join-Path $stagingDir "example.env")
    Write-Host "  + example.env (template, DO NOT rename to .env manually)" -ForegroundColor DarkGray
}

# Empty runtime dirs so the folder structure is ready on first boot
foreach ($d in @("logs", "data", "recordings")) {
    New-Item -ItemType Directory -Path (Join-Path $stagingDir $d) | Out-Null
    Set-Content -Path (Join-Path $stagingDir "$d\.gitkeep") -Value "" -Encoding utf8
}

# Step 4: zip
Write-Host "[4/4] Compressing..." -ForegroundColor Cyan

if (-not (Test-Path $OutDir)) { New-Item -ItemType Directory -Path $OutDir | Out-Null }
$zipPath = Join-Path $OutDir "$zipName.zip"
if (Test-Path $zipPath) { Remove-Item $zipPath -Force }
Compress-Archive -Path "$stagingDir\*" -DestinationPath $zipPath
Remove-Item $stagingDir -Recurse -Force

$zipSizeMB = [Math]::Round((Get-Item $zipPath).Length / 1MB, 1)

Write-Host ""
Write-Host "========================================" -ForegroundColor Green
Write-Host " ZIP ready : $zipPath" -ForegroundColor Green
Write-Host " Size      : $zipSizeMB MB" -ForegroundColor Green
Write-Host " Commit    : $gitSha" -ForegroundColor Green
Write-Host "========================================" -ForegroundColor Green
Write-Host ""
Write-Host "Deploy on target machine:" -ForegroundColor Cyan
Write-Host "  1. Extract the zip to the desired folder"
Write-Host "  2. Edit config\config.toml with machine-specific values"
Write-Host "  3. Double-click Setup.bat (runs Install.ps1 as admin)"
